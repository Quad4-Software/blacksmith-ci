package integrations

import (
	"context"
	"errors"
	"net"
)

// IsTimeoutError reports whether err represents a context deadline or a network timeout.
// Provider implementations should use this to distinguish ErrProviderTimeout from
// other failure modes (bad credentials, unhealthy server, refused connection).
func IsTimeoutError(err error) bool {
	if errors.Is(err, context.DeadlineExceeded) {
		return true
	}
	var netErr net.Error
	if errors.As(err, &netErr) && netErr.Timeout() {
		return true
	}
	return false
}
