func TestParseJSONArray(t *testing.T) {
	themes, err := Parse([]byte(`[
		{
			"id": "acme",
			"name": "ACME",
			"description": "Corporate colors",
			"base": "claude",
			"light": {"primary": "#7c3aed", "--sidebar-primary": " oklch(0.5 0.2 290) ", "radius": "1rem"},
			"dark": {"primary": "#a78bfa"}
		},
		{
			"id": "tweakcn",
			"cssVars": {
				"theme": {"font-sans": "Inter"},
				"light": {"background": "oklch(1 0 0)"},
				"dark": {"background": "oklch(0.2 0 0)"}
			}
		},
		{"id": "light-only", "light": {"primary": "red"}}
	]`), "themes.json")
	require.NoError(t, err)

	assert.Equal(t, []Theme{
		{
			ID:          "acme",
			Name:        "ACME",
			Description: "Corporate colors",
			Base:        "claude",
			Light:       map[string]string{"primary": "#7c3aed", "sidebar-primary": "oklch(0.5 0.2 290)"},
			Dark:        map[string]string{"primary": "#a78bfa"},
		},
		{
			ID:    "tweakcn",
			Light: map[string]string{"background": "oklch(1 0 0)"},
			Dark:  map[string]string{"background": "oklch(0.2 0 0)"},
		},
		{ID: "light-only", Light: map[string]string{"primary": "red"}},
	}, themes)
}

