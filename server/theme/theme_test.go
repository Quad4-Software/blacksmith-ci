func TestParseCSS(t *testing.T) {
	themes, err := Parse([]byte(`
		/* generated by tweakcn */
		:root {
			--background: oklch(1 0 0);
			--primary: #7c3aed !important;
			--font-sans: "Inter", sans-serif;
			--radius: 0.5rem;
			color: red;
		}
		.dark, [data-theme="dark"] {
			--primary: #a78bfa;
		}
		.sidebar { --primary: blue; }
		@theme inline {
			--color-primary: var(--primary);
		}
	`), "theme-ACME Corp.css")
	require.NoError(t, err)

	assert.Equal(t, []Theme{{
		ID:    "acme-corp",
		Name:  "Acme Corp",
		Light: map[string]string{"background": "oklch(1 0 0)", "primary": "#7c3aed"},
		Dark:  map[string]string{"primary": "#a78bfa"},
	}}, themes)
}

func TestParseErrors(t *testing.T) {
	tests := []struct {
		name  string
		input string
		file  string
		err   string
	}{
		{"invalid json array", `[`, "t.json", "invalid JSON array"},
		{"not json or css", `hello`, "t.txt", "neither JSON nor CSS"},
		{"missing id in array", `[{"light": {"primary": "red"}}, {"id": "b", "light": {"primary": "red"}}]`, "t.json", `id "" must match`},
		{"invalid id", `[{"id": "My Theme", "light": {"primary": "red"}}]`, "t.json", `id "My Theme" must match`},
		{"unnamable css", `:root { --primary: red; }`, "/", `id "" must match`},
		{"duplicate id", `[{"id": "a", "light": {"primary": "red"}}, {"id": "a", "light": {"primary": "red"}}]`, "t.json", "duplicate id"},
		{"no colors", `[{"id": "a", "name": "A"}]`, "t.json", "defines no theme colors"},
		{"only unknown vars", `:root { --radius: 1rem; }`, "a.css", "defines no theme colors"},
		{"empty value", `[{"id": "a", "light": {"primary": ""}}]`, "t.json", "empty value"},
		{"injection", `[{"id": "a", "light": {"primary": "red} body {display: none"}}]`, "t.json", "contains one of"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := Parse([]byte(tt.input), tt.file)
			assert.ErrorContains(t, err, tt.err)
		})
	}
}

func TestLoad(t *testing.T) {
	dir := t.TempDir()
	write := func(name, content string) string {
		p := filepath.Join(dir, name)
		require.NoError(t, os.WriteFile(p, []byte(content), 0o600))
		return p
	}

	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/themes/ocean.css":
			_, _ = w.Write([]byte(`:root { --primary: #0369a1; } .dark { --primary: #38bdf8; }`))
		case "/big.css":
			_, _ = w.Write([]byte(":root { --primary: red; }" + strings.Repeat(" ", maxSourceSize)))
		case "/broken.css":
			_, _ = w.Write([]byte(`nonsense`))
		default:
			http.NotFound(w, r)
		}
	}))
	defer srv.Close()

	t.Run("no sources", func(t *testing.T) {
		themes, err := Load(t.Context(), nil)
		require.NoError(t, err)
		assert.Nil(t, themes)
	})

	t.Run("files and urls", func(t *testing.T) {
		themes, err := Load(t.Context(), []string{
			write("themes.json", `[{"id": "acme", "light": {"primary": "red"}}]`),
			" ",
			srv.URL + "/themes/ocean.css",
		})
		require.NoError(t, err)
		assert.Equal(t, []Theme{
			{ID: "acme", Light: map[string]string{"primary": "red"}},
			{
				ID:    "ocean",
				Name:  "Ocean",
				Light: map[string]string{"primary": "#0369a1"},
				Dark:  map[string]string{"primary": "#38bdf8"},
			},
		}, themes)
	})

	t.Run("unreachable url is skipped", func(t *testing.T) {
		themes, err := Load(t.Context(), []string{srv.URL + "/missing.css", write("b.css", `:root { --primary: red; }`)})
		require.NoError(t, err)
		assert.Equal(t, []Theme{{ID: "b", Name: "B", Light: map[string]string{"primary": "red"}}}, themes)
	})

	t.Run("missing file", func(t *testing.T) {
		_, err := Load(t.Context(), []string{filepath.Join(dir, "missing.json")})
		assert.ErrorContains(t, err, "read custom themes file")
	})

	t.Run("invalid content from url", func(t *testing.T) {
		_, err := Load(t.Context(), []string{srv.URL + "/broken.css"})
		assert.ErrorContains(t, err, srv.URL+"/broken.css")
	})

	t.Run("too large", func(t *testing.T) {
		_, err := Load(t.Context(), []string{srv.URL + "/big.css"})
		assert.ErrorContains(t, err, "larger than")
	})

	t.Run("duplicate id across sources", func(t *testing.T) {
		_, err := Load(t.Context(), []string{write("a.css", `:root { --primary: red; }`), write("a.json", `{"light": {"primary": "red"}}`)})
		assert.ErrorContains(t, err, `theme "a"`)
		assert.ErrorContains(t, err, "already defined")
	})
}
